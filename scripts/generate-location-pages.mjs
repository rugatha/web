import { readFile, writeFile, mkdir, unlink } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { createLocationRenderer } from '../map/scripts/location-render.js';
import { loadLocationChapterCatalog } from './location-chapter-catalog.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = path.join(root, 'map/location');
const marker = '<!-- Generated by scripts/generate-location-pages.mjs -->';
const checkOnly = process.argv.includes('--check');
const scopeIndex = process.argv.indexOf('--scope-file');
const scope = scopeIndex < 0 ? null : new Set(JSON.parse(await readFile(process.argv[scopeIndex + 1], 'utf8'))
  .map(key => `${key ? `${key}/` : ''}index.html`));
const data = JSON.parse(await readFile(path.join(root, 'map/location/assets/location.json'), 'utf8'));
const chapterCatalog = await loadLocationChapterCatalog(data);
const catalogPath = path.join(output, 'assets/chapter-catalog.json');
const catalogJson = `${JSON.stringify(chapterCatalog, null, 2)}\n`;
const { render, children, image, url } = createLocationRenderer(data, 'zh', chapterCatalog);
const pages = new Map();

function visit(node, depth = 0, segments = [], ancestors = []) {
  if (!node || typeof node.name_en !== 'string' || !node.desc_zh?.trim()) throw new Error(`Missing name/description: ${segments.join('/')}`);
  if (depth > 0 && !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(node.slug)) throw new Error(`Unsafe slug: ${node.slug}`);
  const imagePath = image(node);
  const firebaseImage = typeof imagePath === 'string' && /^https:\/\/firebasestorage\.googleapis\.com\/v0\/b\/rugatha-87e15\.firebasestorage\.app\/o\/public-images%2Flocations%2F[a-z0-9_-]+%2F[a-f0-9]{64}%2Freading\.png\?alt=media$/.test(imagePath);
  if (!firebaseImage) throw new Error(`Location art must use Firebase Storage: ${imagePath}`);
  for (const key of ['chapters']) {
    if (node[key] !== undefined && !Array.isArray(node[key])) throw new Error(`Invalid chapter list: ${segments.join('/')}`);
    const ids = new Set();
    for (const chapter of node[key] ?? []) {
      if (!chapter.id || !chapter.title_zh || !chapter.url?.startsWith('/campaigns/pages/') || chapter.url.includes('..') || ids.has(chapter.id)) throw new Error(`Invalid chapter: ${segments.join('/')} / ${chapter.id}`);
      ids.add(chapter.id);
    }
  }
  const filename = [...segments, 'index.html'].join('/');
  if (pages.has(filename)) throw new Error(`Duplicate page: ${filename}`);
  pages.set(filename, render(node, depth, segments, ancestors));
  for (const child of children(node, depth)) visit(child, depth + 1, [...segments, child.slug], [...ancestors, { node, href: url(segments) }]);
}

if (data.schema_version !== 1 || !Array.isArray(data.realms)) throw new Error('Expected nested location.json schema version 1.');
visit(data);
const manifestPath = path.join(output, '.generated-pages.json');
let previous = [];
try { previous = JSON.parse(await readFile(manifestPath, 'utf8')); }
catch (error) { if (error.code !== 'ENOENT') throw error; }
for (const [filename, html] of pages) {
  if (scope && !scope.has(filename)) continue;
  const target = path.join(output, filename);
  if (checkOnly) {
    if (await readFile(target, 'utf8') !== html) throw new Error(`Page needs regeneration: ${filename}`);
  } else {
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, html);
  }
}
for (const filename of previous.filter(filename => !pages.has(filename))) {
  if (scope && !scope.has(filename)) continue;
  if (!/^(?:[a-z0-9-]+\/)*index\.html$/.test(filename)) throw new Error(`Unsafe manifest entry: ${filename}`);
  if (checkOnly) throw new Error(`Obsolete generated page: ${filename}`);
  const target = path.join(output, filename);
  // Only remove stale pages created by this generator, never arbitrary files.
  if (!(await readFile(target, 'utf8')).includes(marker)) throw new Error(`Refusing to remove edited page: ${filename}`);
  await unlink(target);
}
const selected = [...pages.keys()].filter(filename => !scope || scope.has(filename));
if (checkOnly) {
  if (await readFile(catalogPath, 'utf8') !== catalogJson) throw new Error('Chapter catalog needs regeneration.');
} else await writeFile(catalogPath, catalogJson);
if (!checkOnly) {
  const manifest = scope ? [...new Set([...previous.filter(filename => !scope.has(filename)), ...selected])] : selected;
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
}
console.log(`${checkOnly ? 'Verified' : 'Generated'} ${selected.length} location pages from map/location/assets/location.json${scope ? ' (scoped)' : ''}.`);
