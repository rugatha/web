// Shared rendering for generated HTML and live JSON updates.
export function createLocationRenderer(data, language = 'zh', chapterCatalog = {}) {
const base = '/map/location/';
const marker = '<!-- Generated by scripts/generate-location-pages.mjs -->';
const escape = value => String(value ?? '').replace(/[&<>"']/g, char => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
}[char]));
const en = language === 'en';
const t = (zh, english) => en ? english : zh;
const localized = (node, field) => [node[`${field}_${en ? 'en' : 'zh'}`], node[`${field}_${en ? 'zh' : 'en'}`]].find(value => typeof value === 'string' && value.trim()) || '';
const label = node => localized(node, 'name');
const description = node => localized(node, 'desc');
const levels = en ? ['Location Atlas', 'Realm', 'Kingdom', 'City', 'Location'] : ['地點圖鑑', '時空', '國家', '城鎮', '地點'];
const childKeys = ['realms', 'kingdoms', 'cities', 'pois'];
const childLabels = en ? ['Explore realms', 'Explore kingdoms', 'Explore cities', 'Explore local places'] : ['探索時空', '探索國家', '探索城鎮', '探索城內與周邊地點'];
const units = en ? ['realms', 'kingdom groups', 'cities', 'locations'] : ['個時空', '個國家分組', '座城鎮', '處地點'];

function children(node, depth) { return node[childKeys[depth]] ?? []; }
function image(node) { return node.image || data.image; }
function url(segments) { return `${base}${segments.length ? `${segments.join('/')}/` : ''}`; }
function totals(node, depth) {
  const counts = { cities: depth === 3 ? 1 : 0, pois: depth === 4 ? 1 : 0 };
  for (const child of children(node, depth)) {
    const sub = totals(child, depth + 1);
    counts.cities += sub.cities;
    counts.pois += sub.pois;
  }
  return counts;
}

function card(node, href, depth) {
  const count = depth < 4 ? `${children(node, depth).length} ${units[depth]}` : t('閱讀地點故事', 'Read location stories');
  return `<li><a class="location-card" href="${escape(href)}">
    <div class="location-card__image"><img data-location-art="${escape(href)}" src="${escape(image(node))}" alt="${escape(label(node))}" loading="lazy" decoding="async" width="720" height="405"></div>
    <div class="location-card__body"><p class="location-card__type">${levels[depth]}<span>${escape(count)}</span></p>
      <h3>${escape(label(node))}</h3><p class="location-card__desc">${escape(description(node).split(/\r?\n/, 1)[0])}</p>
      <span class="location-card__link">${depth === 4 ? t('認識這個地點', 'Discover this place') : t('繼續探索', 'Explore more')} <span aria-hidden="true">→</span></span>
    </div></a></li>`;
}

function chapterSection(node) {
  const actual = node.chapters ?? [];
  const campaigns = new Map();
  for (const chapter of actual) {
    const metadata = chapterCatalog[chapter.id];
    if (!metadata) throw new Error(`Missing chapter catalog entry: ${chapter.id}`);
    const { campaign, arc } = metadata;
    if (!campaigns.has(campaign.id)) campaigns.set(campaign.id, { ...campaign, arcs: new Map(), count: 0 });
    const group = campaigns.get(campaign.id);
    if (!group.arcs.has(arc.id)) group.arcs.set(arc.id, { ...arc, chapters: [] });
    group.arcs.get(arc.id).chapters.push({ ...chapter, image: metadata.image });
    group.count++;
  }
  const chapterCard = chapter => `<li><a class="location-chapter-card" href="${escape(chapter.url)}">
    <div class="location-chapters__image"><img src="${escape(chapter.image)}" alt="" loading="lazy" decoding="async" width="720" height="405"></div>
    <div class="location-chapters__body"><span class="location-chapters__type">${t('章節', 'Chapter')}</span><h5 class="location-chapters__title">${escape(localized(chapter, 'title'))}</h5>${chapter.date ? `<span class="location-chapters__date">${escape(chapter.date)}</span>` : ''}
      <span class="location-chapters__link">${t('閱讀章節', 'Read chapter')}<span aria-hidden="true">→</span></span>
    </div></a></li>`;
  const grouped = [...campaigns.values()].map(campaign => `<details class="location-campaign" data-chapter-group="${escape(campaign.id)}"${actual.length <= 8 ? ' open' : ''}>
    <summary><div class="location-campaign__heading"><span class="location-story__level">${t('團務', 'Campaign')}</span><h3>${escape(campaign.name)}</h3></div><span class="location-campaign__count"><span>${campaign.arcs.size} ${t('個故事弧', 'story arcs')}</span><span>${campaign.count} ${t('篇章節', 'chapters')}</span></span></summary>
    <div class="location-campaign__body"><a class="location-campaign__link" href="${escape(campaign.url)}">${t('查看團務', 'View campaign')} <span aria-hidden="true">↗</span></a>
      ${[...campaign.arcs.values()].map(arc => `<section class="location-story-arc"><div class="location-story-arc__heading"><div><span class="location-story__level">${t('故事弧', 'Story arc')}</span><h4><a href="${escape(arc.url)}">${escape(localized(arc, 'title'))}</a></h4></div><span>${arc.chapters.length} ${t('篇章節', 'chapters')}</span></div>
      <ul class="location-chapters">${arc.chapters.map(chapterCard).join('')}</ul></section>`).join('')}
    </div></details>`).join('');
  return `<section class="location-section location-story" aria-labelledby="chapters-heading">
    <div class="section-heading"><h2 id="chapters-heading">${t('相關章節', 'Related chapters')}</h2><span>${actual.length} ${t('篇故事', 'stories')}</span></div>
    <p class="location-story__intro">${t('發生在這裡的故事，依團務與故事弧整理。', 'Stories set here, organized by campaign and story arc.')}</p>
    ${actual.length ? grouped : `<p class="location-empty">${t('目前尚未收錄以此地為發生地點的章節。', 'No chapters set here have been added yet.')}</p>`}
  </section>`;
}

function render(node, depth, segments, ancestors) {
  const title = label(node);
  const pageDescription = description(node);
  const href = url(segments);
  const count = totals(node, depth);
  const direct = children(node, depth);
  const parent = ancestors.at(-1);
  const crumbs = [{ node: { name_zh: '首頁', name_en: 'Home' }, href: '/' }, ...ancestors, { node, href }];
  const breadcrumbs = crumbs.map((item, index) => `<li>${index === crumbs.length - 1
    ? `<span aria-current="page">${escape(depth === 0 ? levels[0] : label(item.node))}</span>`
    : `<a href="${escape(item.href)}">${escape(item.href === base ? levels[0] : label(item.node))}</a>`}</li>`).join('');
  let section;
  if (depth < 4) {
    section = `<section class="location-section" aria-labelledby="children-heading">
      <div class="section-heading"><h2 id="children-heading">${childLabels[depth]}</h2><span>${direct.length} ${units[depth]}</span></div>
      ${direct.length ? `<ul class="location-grid">${direct.map(child => card(child, url([...segments, child.slug]), depth + 1)).join('')}</ul>`
        : `<p class="location-empty">${t('此城鎮尚未收錄個別地點。', 'No individual locations have been added to this city yet.')}</p>`}
    </section>`;
  } else {
    const siblings = parent.node.pois;
    const index = siblings.findIndex(item => item.slug === node.slug);
    const neighbors = [siblings[index - 1], siblings[index + 1]].filter(Boolean);
    section = `<section class="location-section" aria-labelledby="children-heading">
      <div class="section-heading"><h2 id="children-heading">${t('同城其他地點', 'Other places in this city')}</h2><a href="${escape(parent.href)}">${t(`查看全部 ${siblings.length} 處地點`, `View all ${siblings.length} locations`)} <span aria-hidden="true">→</span></a></div>
      ${neighbors.length ? `<ul class="location-grid location-grid--neighbors">${neighbors.map(sibling => card(sibling, `${parent.href}${sibling.slug}/`, 4)).join('')}</ul>` : `<p class="location-empty">${t('目前是這座城鎮唯一收錄的地點。', 'This is the only location currently listed in this city.')}</p>`}
    </section>`;
  }
  return `<!DOCTYPE html>
${marker}
<html lang="${en ? 'en' : 'zh-Hant'}">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${escape(depth === 0 ? title : `${title} | Rugatha ${levels[0]}`)}</title>
  <meta name="description" content="${escape(pageDescription)}">
  <link rel="canonical" href="https://rugatha.com${href}">
  <meta property="og:type" content="website">
  <meta property="og:locale" content="${en ? 'en_US' : 'zh_TW'}">
  <meta property="og:title" content="${escape(title)} | Rugatha">
  <meta property="og:description" content="${escape(pageDescription)}">
  <meta property="og:url" content="https://rugatha.com${href}">
  <meta property="og:image" content="${escape(new URL(image(node), 'https://rugatha.com').href)}">
  <link rel="icon" href="/assets/logo/rugatha-favicon.png" type="image/png">
  <link rel="stylesheet" href="/shared/styles/theme.css">
  <link rel="stylesheet" href="/map/styles/locations.css">
  <script src="/shared/language-toggle.js"></script>
  <script type="module" src="/map/scripts/location-page.js"></script>
  <script src="/shared/firebase.config.js"></script>
  <script type="module" src="/shared/auth.js"></script>
</head>
<body>
  <a class="skip-link" href="#main">${t('跳至主要內容', 'Skip to content')}</a>
  <header class="atlas-header">
    <div class="banner" aria-label="Rugatha banner image"><a class="banner-link" href="/" aria-label="${t('前往 Rugatha 首頁', 'Go to Rugatha home')}"><img class="banner-logo" src="/assets/banner/rugatha-banner-trademark.png" alt="Rugatha banner" width="720" height="517"></a></div>
    <nav class="atlas-navigation" aria-label="${t('主選單', 'Main navigation')}"><a href="/map/map/">${t('卓尼森島地圖', 'Dranison Map')}</a><a href="${base}"${depth === 0 ? ' aria-current="page"' : ''}>${levels[0]}</a></nav>
  </header>
  <div class="location-language-toggle" role="group" aria-label="Language"><button class="location-language-button" type="button" data-lang="${en ? 'en' : 'zh'}" data-lang-toggle aria-pressed="true" aria-label="${t('目前語言：中文，切換為 English', 'Current language: English, switch to Chinese')}"></button></div>
  <main class="atlas-shell" id="main">
    <nav class="breadcrumbs" aria-label="${t('麵包屑', 'Breadcrumbs')}"><ol>${breadcrumbs}</ol></nav>
    <section class="location-hero${depth === 0 ? ' location-hero--overview' : ''}" aria-labelledby="page-heading">
      <div class="location-hero__copy"><p class="eyebrow">${levels[depth]}</p>
        <h1 id="page-heading">${escape(title)}</h1><p class="location-description">${escape(pageDescription)}</p>
        <div class="location-meta">${depth < 3 ? `<span>${count.cities} ${units[2]}</span>` : ''}${depth < 4 ? `<span>${count.pois} ${units[3]}</span>` : `<span>${escape(label(parent.node))}</span>`}</div>
        ${parent ? `<a class="parent-link" href="${escape(parent.href)}"><span aria-hidden="true">←</span> ${t('返回', 'Back to ')}${levels[depth - 1]}${t('：', ': ')}${escape(label(parent.node))}</a>` : `<a class="parent-link" href="/map/map/">← ${t('查看卓尼森島地圖', 'View Dranison Map')}</a>`}
      </div>
      ${depth > 0 ? `<figure class="location-hero__image"><img data-location-art="${escape(href)}" src="${escape(image(node))}" alt="${escape(title)}" width="960" height="540" fetchpriority="high"></figure>` : ''}
    </section>
    ${depth === 0 ? section : depth === 4 ? chapterSection(node) + section : section + chapterSection(node)}
  </main>
  <footer class="atlas-footer">
    <nav aria-label="${t('返回導覽', 'Return navigation')}">${depth > 0 ? `<a class="back-link" href="${base}"><span aria-hidden="true">↩︎</span>${t('返回地點圖鑑', 'Back to Location Atlas')}</a>` : ''}<a class="back-link" href="/map/map/"><span aria-hidden="true">↩︎</span>${t('返回卓尼森島地圖', 'Back to Dranison Map')}</a></nav>
  </footer>
</body>
</html>
`;
}

return { render, children, image, url };
}
